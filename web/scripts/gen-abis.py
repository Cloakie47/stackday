"""Regenerates web/lib/abis.ts and web/lib/deployment.json from the Foundry build output.
Run from the repository root after `forge build`:  python web/scripts/gen-abis.py
"""
import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONTRACTS = {
    "payrollAbi": "Payroll.sol/Payroll.json",
    "vaultAbi": "EmployeeVault.sol/EmployeeVault.json",
    "factoryAbi": "VaultFactory.sol/VaultFactory.json",
    "routerAbi": "SipRouter.sol/SipRouter.json",
    "lendingAdapterAbi": "MorphoLendingAdapter.sol/MorphoLendingAdapter.json",
    "mockFeedAbi": "Mocks.sol/MockPriceFeed.json",
    "mockStockAbi": "Mocks.sol/MockStockToken.json",
    "mockSwapAbi": "Mocks.sol/MockSwapAdapter.json",
    "giftBoxAbi": "GiftBox.sol/GiftBox.json",
    "mockSellDeskAbi": "Mocks.sol/MockSellDesk.json",
}

out = ["// GENERATED by web/scripts/gen-abis.py from the Foundry build. Do not edit by hand.\n"]
for name, path in CONTRACTS.items():
    abi = json.load(io.open(os.path.join(ROOT, "out", path), encoding="utf-8"))["abi"]
    out.append("export const %s = %s as const;\n" % (name, json.dumps(abi)))
io.open(os.path.join(ROOT, "web", "lib", "abis.ts"), "w", encoding="utf-8", newline="\n").write("\n".join(out))

dep = json.load(io.open(os.path.join(ROOT, "deployments", "base-sepolia.json"), encoding="utf-8"))
io.open(os.path.join(ROOT, "web", "lib", "deployment.json"), "w", encoding="utf-8", newline="\n").write(
    json.dumps(dep, indent=2) + "\n"
)
print("wrote web/lib/abis.ts and web/lib/deployment.json")
